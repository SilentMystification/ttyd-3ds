#!/usr/bin/env python3
"""Write port3ds/sources_<version>.cmake from the object list in configure.py.

The 3DS build compiles exactly the game and REL sources the matching build
links for that version. configure.py lists every object of every version;
which ones a version has comes from its splits (config/<version>/splits.txt
for the DOL, config/<version>/<rel>/splits.txt for each REL).

Libraries under libs/ are listed separately: MusyX is compiled for the port
(with its 3DS backend); the Dolphin SDK, MSL, runtime and TRK are replaced by
port3ds/sdk and newlib and are not listed.

Same approach as paper-cut's tools/port/gen_sources.py (MIT).

Usage: tools/port3ds/gen_sources.py [--version G8ME01]
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def read_configure():
    text = open(os.path.join(ROOT, "configure.py"), encoding="utf-8").read()
    return text[: text.index("if args.mode ==")]


def load_config(text, version):
    argv = sys.argv
    sys.argv = ["configure.py", "--version", version]
    sys.path.insert(0, ROOT)
    g = {"__name__": "configure", "__file__": os.path.join(ROOT, "configure.py")}
    cwd = os.getcwd()
    os.chdir(ROOT)
    try:
        exec(compile(text, "configure.py", "exec"), g)
    finally:
        os.chdir(cwd)
        sys.argv = argv
    return g["config"].libs


def split_units(version, rel=None):
    p = os.path.join(ROOT, "config", version, *([rel] if rel else []), "splits.txt")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        return {m.group(1) for m in re.finditer(r"(?m)^(\S[^\n]*?):\s*$", f.read()) if m.group(1) != "Sections"}


# MusyX's GameCube DSP and AI layer and the DSP microcode. The port runs
# MusyX's PC target instead: the same DSP command lists (hw_dspctrl.c),
# executed by the software mixer (hw_pcmixer.c), with ARAM in memory
# (hw_aramdma.c) and the AI/DSP glue in port3ds/game/audio.c.
MUSYX_HARDWARE = {
    "libs/musyx/src/musyx/runtime/hw_dolphin.c",
    "libs/musyx/src/musyx/runtime/dsp_import.c",
}
# Port-only MusyX sources (not GameCube objects).
MUSYX_PORT = ["libs/musyx/src/musyx/runtime/hw_pcmixer.c"]


def resolve(path):
    """The path as it exists on disk, matching names without case (configure.py
    names HARDWARE.C, the file is hardware.c), or None."""
    cur = ROOT
    for part in path.split("/"):
        if os.path.exists(os.path.join(cur, part)):
            cur = os.path.join(cur, part)
            continue
        found = [e for e in os.listdir(cur) if e.lower() == part.lower()] if os.path.isdir(cur) else []
        if len(found) != 1:
            return None
        cur = os.path.join(cur, found[0])
    return os.path.relpath(cur, ROOT)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version", default="G8ME01")
    args = ap.parse_args()

    libs = load_config(read_configure(), args.version)
    dol_units = split_units(args.version)
    dol, rels, musyx = [], {}, []
    for lib in libs:
        src_dir = lib.get("src_dir", "src")
        is_rel = src_dir.startswith("rels/")
        is_musyx = src_dir.startswith("libs/musyx")
        if src_dir.startswith("libs/") and not is_musyx:
            continue
        units = split_units(args.version, lib["lib"]) if is_rel else dol_units
        if units is None:
            continue
        for obj in lib["objects"]:
            if not obj.completed:
                continue
            name = obj.options.get("source") or obj.name
            if obj.name not in units and name not in units:
                continue
            path = os.path.normpath(f"{src_dir}/{name}")
            if not path.lower().endswith(".c"):
                continue
            found = resolve(path)
            if found is None:
                sys.exit(f"gen_sources: {path} is a completed object of {args.version} but is not on disk")
            path = found
            if path in MUSYX_HARDWARE:
                continue
            if is_rel:
                rels.setdefault(lib["lib"], []).append(path)
            elif is_musyx:
                musyx.append(path)
            else:
                dol.append(path)

    musyx += MUSYX_PORT
    out = [f"# Generated by tools/port3ds/gen_sources.py from configure.py ({args.version}). Do not edit.",
           "set(TTYD_DOL_SOURCES"]
    out += [f"    ${{TTYD_REPO_DIR}}/{p}" for p in dol] + [")"]
    out.append("set(TTYD_MUSYX_SOURCES")
    out += [f"    ${{TTYD_REPO_DIR}}/{p}" for p in musyx] + [")"]
    out.append(f"set(TTYD_RELS {' '.join(sorted(rels))})")
    for name in sorted(rels):
        out.append(f"set(TTYD_REL_{name}_SOURCES")
        out += [f"    ${{TTYD_REPO_DIR}}/{p}" for p in rels[name]] + [")"]
    dest = os.path.join(ROOT, "port3ds", f"sources_{args.version}.cmake")
    with open(dest, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{args.version}: dol {len(dol)} files, musyx {len(musyx)} files, "
          f"rels {len(rels)} ({sum(map(len, rels.values()))} files) -> {os.path.relpath(dest, ROOT)}")


if __name__ == "__main__":
    main()
