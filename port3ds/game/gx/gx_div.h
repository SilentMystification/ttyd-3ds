static inline u32 port_div_alpha(u32 n, u32 sw) { return (u32)(((u64)n * s_alpha_recip[sw]) >> 28); }

/* cols[i] = i * w / pw for i < pw, the source column of destination column i. False when pw is
 * too large for the table. One divide per column instead of one per texel. */
#define GX_COLS_MAX 1024
static inline int gx_build_cols(u16* cols, u32 w, u32 pw) {
    if (pw > GX_COLS_MAX || w > 65535) {
        return 0;
    }
    for (u32 i = 0; i < pw; i++) {
        cols[i] = (u16)(i * w / pw);
    }
    return 1;
}

