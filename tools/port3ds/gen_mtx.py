#!/usr/bin/env python3
"""Generate the 3DS port's matrix library from the decomp's SDK sources.

    gen_mtx.py OUT.c

The Dolphin SDK has each matrix and vector function twice: C_MTX*/C_VEC*
in plain C and PSMTX*/PSVEC* with paired-single assembly. The port copies
every C_ function definition from libs/dolsdk2004/src/mtx/*.c unchanged and
defines each PS name as a call to its C_ twin, so the game gets the SDK's
own math. (Paired-single code fuses multiply-adds, so the last bit of some
results can differ from the GameCube's.)
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCES = ["mtx.c", "mtx44.c", "mtxvec.c", "mtx44vec.c", "vec.c", "quat.c", "mtxstack.c"]
DEF = re.compile(r"^(?:static\s+)?(?:inline\s+)?(void|f32|u32|BOOL|s32)\s+(C_\w+)\s*\(([^)]*)\)\s*\{", re.M)


def extract(text):
    out = []
    for m in DEF.finditer(text):
        start = m.start()
        # the body ends at the first line that is exactly "}"
        end = text.index("\n}\n", m.end()) + 3
        out.append((m.group(1), m.group(2), m.group(3), text[start:end]))
    return out


def main():
    dest = Path(sys.argv[1])
    funcs = []
    seen = set()
    defines = []
    for name in SOURCES:
        path = REPO / "libs" / "dolsdk2004" / "src" / "mtx" / name
        if path.exists():
            src_lines = path.read_text().splitlines()
            i = 0
            while i < len(src_lines):
                line = src_lines[i]
                if line.startswith("#define") and "ASSERT" not in line:
                    block = [line]
                    while block[-1].rstrip().endswith("\\") and i + 1 < len(src_lines):
                        i += 1
                        block.append(src_lines[i])
                    text = "\n".join(block)
                    if text not in defines:
                        defines.append(text)
                i += 1
    for name in SOURCES:
        path = REPO / "libs" / "dolsdk2004" / "src" / "mtx" / name
        if not path.exists():
            continue
        for ret, fn, args, body in extract(path.read_text()):
            if fn in seen:
                continue
            seen.add(fn)
            funcs.append((ret, fn, args, body, name))

    lines = [
        "/* Generated by tools/port3ds/gen_mtx.py from libs/dolsdk2004/src/mtx. Do not edit. */",
        "#include <dolphin/mtx.h>",
        "#include <math.h>",
        "#include <string.h>",
        "#define ASSERTMSGLINE(line, cond, msg) ((void)0)",
        "#define ASSERTLINE(line, cond) ((void)0)",
        "",
    ]
    lines += defines + [""]
    for ret, fn, args, body, src in funcs:
        lines.append(f"/* {src} */")
        lines.append(body)
    lines.append("/* PS entry points: the C versions above. */")
    for ret, fn, args, body, src in funcs:
        ps = "PS" + fn[2:]
        arg_names = []
        for a in args.split(","):
            a = a.strip()
            if not a or a == "void":
                continue
            m = re.search(r"(\w+)\s*(\[[^\]]*\])*\s*$", a)
            arg_names.append(m.group(1))
        call = f"{fn}({', '.join(arg_names)})"
        stmt = f"return {call};" if ret != "void" else f"{call};"
        lines.append(f"{ret} {ps}({args}) {{ {stmt} }}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n")
    print(f"gen_mtx: {len(funcs)} functions -> {dest}")


if __name__ == "__main__":
    main()
